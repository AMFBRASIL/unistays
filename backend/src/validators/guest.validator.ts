export const addLoyaltyPointsSchema = z.object({
  body: z.object({
    operation: z.enum(['credit', 'debit'], { required_error: 'Operação é obrigatória (credit ou debit)' }),
    points: z.number().int().min(1, 'Quantidade deve ser pelo menos 1'),
    source: z.string().max(80).optional().default('manual'),
    description: z.string().max(500).optional().nullable(),
  }),
});

export type CreateGuestInput = z.infer<typeof createGuestSchema>['body'];
export type UpdateGuestInput = z.infer<typeof updateGuestSchema>['body'];
export type AddLoyaltyPointsInput = z.infer<typeof addLoyaltyPointsSchema>['body'];
